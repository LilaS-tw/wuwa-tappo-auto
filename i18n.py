def map_language_tag(tag: str):
    """把 BCP-47 語言標籤對應到 Tappo 代碼（規則同 Tappo 前端）。"""
    n = (tag or "").strip().lower()
    if not n:
        return None
    if n.startswith(("zh-tw", "zh-hk", "zh-hant")):
        return "tw"
    if n.startswith("ja"):
        return "jp"
    if n.startswith("ko"):
        return "kr"
    for pref, code in (("fr", "fr"), ("de", "de"), ("es", "es"), ("pt", "pt"), ("th", "th"), ("en", "en")):
        if n.startswith(pref):
            return code
    return None


def _read_tappo_ui_locale():
    try:
        with open(config.ui_locale_path(), "r", encoding="utf-8") as f:
            value = f.read().strip().lower()
    except OSError:
        return None
    return value if value in CATALOG else None


def _os_ui_locale():
    try:
        buf = ctypes.create_unicode_buffer(85)  # LOCALE_NAME_MAX_LENGTH
        if ctypes.windll.kernel32.GetUserDefaultLocaleName(buf, len(buf)):
            return map_language_tag(buf.value)
    except Exception:
        pass
    return None


def detect_locale() -> str:
    """母語偵測：Tappo ui-locale.txt → 作業系統語言 → 英文。"""
    return _read_tappo_ui_locale() or _os_ui_locale() or "en"


def set_locale(code: str) -> str:
    global _current
    _current = detect_locale() if code in (None, "auto") else (code if code in CATALOG else "en")
    return _current


def get_locale() -> str:
    return _current


def t(key: str, **kwargs) -> str:
    template = CATALOG.get(_current, {}).get(key)
    if template is None:
        template = CATALOG["en"].get(key, key)
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return template
